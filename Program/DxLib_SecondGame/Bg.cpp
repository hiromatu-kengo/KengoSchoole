void Bg::Draw()
{
	//背景の空色を表示する
	DrawBox(0, 0, Game::kScreenWidth, Game::kScreenHeight, GetColor(106, 90, 205), true);
//	DrawRectGraph(64, 64, 0, 0, kChipWidth, kChipHeight, m_graphHandle, true);
	for (int y = 0;y < kChipNumY;y++)
	{
		for (int x = 0;x < kChipNumX;x++)
		{
			int chipNo = kChipData[y][x];
			if (chipNo < 0)continue;
			int indexX = chipNo % kGraphChipNumX;
			int indexY = chipNo / kGraphChipNumX;
			DrawRectGraph(x * kChipWidth, y * kChipHeight, indexX * kChipWidth, indexY * kChipHeight, kChipWidth, kChipHeight, m_graphHandle, true);
		}
	}
//	DrawLine(0, kFieldY, Game::kScreenWidth, kFieldY, GetColor(255, 255, 255));
}
